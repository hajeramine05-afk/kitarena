import type { Language, OrderStatus } from './types';

export function pickLang(lang: Language, fr: string, ar: string): string {
  return lang === 'ar' ? (ar || fr) : fr;
}

export function formatMad(amount: number, lang: Language): string {
  const formatted = new Intl.NumberFormat(lang === 'ar' ? 'fr-MA' : 'fr-MA').format(amount);
  return lang === 'ar' ? `${formatted} د.م.` : `${formatted} MAD`;
}

export function formatDateTime(iso: string, lang: Language): string {
  try {
    return new Intl.DateTimeFormat(lang === 'ar' ? 'ar-MA' : 'fr-FR', {
      dateStyle: 'medium',
      timeStyle: 'short',
    }).format(new Date(iso));
  } catch {
    return iso;
  }
}

